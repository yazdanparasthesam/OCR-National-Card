"""Accuracy benchmark for the OCR pipeline.

Runs the full pipeline over a dataset of card images with ground-truth JSON (either
generated by ``scripts/generate_synthetic_cards.py`` or your own annotated cards)
and reports, per field, the exact-match rate, the character accuracy and the mean
confidence.

Examples::

    python scripts/benchmark.py --generate 30 --difficulty clean
    python scripts/benchmark.py --generate 30 --difficulty photo --out reports/benchmark_photo.md
    python scripts/benchmark.py --dataset data/samples            # your own folder
    python scripts/benchmark.py --generate 10 --difficulty hard --no-cache
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
import time
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from nidocr.config import PROJECT_ROOT, Settings  # noqa: E402
from nidocr.fields.definitions import FIELD_ORDER  # noqa: E402
from nidocr.metrics import character_accuracy, exact_match  # noqa: E402
from nidocr.pipeline import NationalCardOCR  # noqa: E402


def load_dataset(dataset: Path) -> list[tuple[Path, dict]]:
    records: list[tuple[Path, dict]] = []
    for truth_path in sorted(dataset.glob("*.json")):
        payload = json.loads(truth_path.read_text(encoding="utf-8"))
        image_name = payload.get("image") or truth_path.with_suffix(".jpg").name
        image_path = dataset / image_name
        if not image_path.is_file():
            for suffix in (".png", ".jpeg", ".JPG"):
                candidate = dataset / Path(image_name).with_suffix(suffix).name
                if candidate.is_file():
                    image_path = candidate
                    break
        if image_path.is_file():
            records.append((image_path, payload))
    return records


def run(
    records: list[tuple[Path, dict]],
    *,
    ocr: NationalCardOCR,
    difficulties: list[str] | None = None,
    verbose: bool = True,
) -> dict:
    per_field: dict[str, list[dict]] = defaultdict(list)
    card_scores: list[float] = []
    timings: list[float] = []
    failures: list[dict] = []
    confidences: dict[str, list[float]] = defaultdict(list)
    validated: dict[str, list[bool]] = defaultdict(list)

    for index, (image_path, truth) in enumerate(records, start=1):
        difficulty = truth.get("difficulty", "custom")
        if difficulties and difficulty not in difficulties:
            continue
        expected = truth.get("fields", {})
        started = time.perf_counter()
        result = ocr.extract(image_path, template=truth.get("template"))
        elapsed = (time.perf_counter() - started) * 1000
        timings.append(elapsed)

        hits = 0
        total = 0
        for key in FIELD_ORDER:
            if key not in expected:
                continue
            predicted = result.fields[key].value if key in result.fields else ""
            reference = str(expected[key])
            matched = exact_match(reference, predicted) if predicted else False
            per_field[key].append(
                {
                    "exact": matched,
                    "accuracy": character_accuracy(reference, predicted) if predicted else 0.0,
                    "difficulty": difficulty,
                }
            )
            confidences[key].append(result.fields[key].confidence if key in result.fields else 0.0)
            validated[key].append(bool(result.fields[key].validated) if key in result.fields else False)
            hits += int(matched)
            total += 1
            if not matched and verbose:
                failures.append(
                    {
                        "image": image_path.name,
                        "field": key,
                        "expected": reference,
                        "predicted": predicted,
                        "confidence": result.fields[key].confidence if key in result.fields else 0.0,
                    }
                )
        if total:
            card_scores.append(hits / total)
        if verbose:
            print(f"  [{index:3}/{len(records)}] {image_path.name:22} {hits}/{total} fields · {elapsed:.0f} ms")

    summary = {
        "cards": len(card_scores),
        "field_exact_match": {},
        "field_character_accuracy": {},
        "field_confidence": {},
        "field_validated_rate": {},
        "overall_exact_match": statistics.fmean(
            [row["exact"] for rows in per_field.values() for row in rows]
        )
        if per_field
        else 0.0,
        "overall_character_accuracy": statistics.fmean(
            [row["accuracy"] for rows in per_field.values() for row in rows]
        )
        if per_field
        else 0.0,
        "perfect_cards": statistics.fmean(card_scores) if card_scores else 0.0,
        "mean_latency_ms": statistics.fmean(timings) if timings else 0.0,
        "failures": failures,
    }
    for key, rows in per_field.items():
        summary["field_exact_match"][key] = statistics.fmean(row["exact"] for row in rows)
        summary["field_character_accuracy"][key] = statistics.fmean(row["accuracy"] for row in rows)
        summary["field_confidence"][key] = statistics.fmean(confidences[key])
        summary["field_validated_rate"][key] = statistics.fmean(validated[key])
    return summary


def to_markdown(summary: dict, *, title: str, dataset: str, settings: Settings) -> str:
    lines = [
        f"# {title}",
        "",
        f"- dataset: `{dataset}`",
        f"- cards: **{summary['cards']}**",
        f"- engine: tesseract (`{settings.languages}`) + glyph digit classifier",
        f"- field exact match: **{summary['overall_exact_match'] * 100:.2f}%**",
        f"- field character accuracy: **{summary['overall_character_accuracy'] * 100:.2f}%**",
        f"- fully correct cards: **{summary['perfect_cards'] * 100:.2f}%**",
        f"- mean latency: {summary['mean_latency_ms']:.0f} ms / card",
        "",
        "| field | exact match | char accuracy | mean confidence | validator pass |",
        "|---|---|---|---|---|",
    ]
    for key in FIELD_ORDER:
        if key not in summary["field_exact_match"]:
            continue
        lines.append(
            f"| `{key}` | {summary['field_exact_match'][key] * 100:.1f}% "
            f"| {summary['field_character_accuracy'][key] * 100:.1f}% "
            f"| {summary['field_confidence'][key]:.1f} "
            f"| {summary['field_validated_rate'][key] * 100:.1f}% |"
        )
    if summary["failures"]:
        lines += ["", "### Misreads", "", "| image | field | expected | predicted | conf |", "|---|---|---|---|---|"]
        for failure in summary["failures"][:25]:
            lines.append(
                f"| {failure['image']} | `{failure['field']}` | {failure['expected']} "
                f"| {failure['predicted'] or '—'} | {failure['confidence']:.0f} |"
            )
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Benchmark the national-card OCR pipeline")
    parser.add_argument("--dataset", default=None, help="folder with images + ground-truth JSON")
    parser.add_argument("--generate", type=int, default=0, help="generate N synthetic cards first")
    parser.add_argument("--difficulty", default="photo", choices=["clean", "photo", "hard"])
    parser.add_argument("--out", default=None, help="write a markdown report here")
    parser.add_argument("--json-out", default=None, help="write raw metrics as JSON")
    parser.add_argument("--title", default="National card OCR benchmark")
    parser.add_argument("--no-cache", action="store_true", help="disable the OCR result cache")
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args()

    settings = Settings()
    if args.no_cache:
        settings = settings.model_copy(update={"cache_ocr": False})

    dataset = Path(args.dataset) if args.dataset else PROJECT_ROOT / "data" / "bench" / args.difficulty
    if args.generate:
        from nidocr.synthetic.renderer import save_dataset

        save_dataset(dataset, count=args.generate, difficulty=args.difficulty, seed=42)
        print(f"generated {args.generate} cards in {dataset}")

    records = load_dataset(dataset)
    if not records:
        print(f"no annotated cards found in {dataset}")
        return 2
    print(f"benchmarking {len(records)} cards from {dataset}")

    ocr = NationalCardOCR(settings)
    summary = run(records, ocr=ocr, verbose=not args.quiet)

    print(f"\nexact match    : {summary['overall_exact_match'] * 100:.2f}%")
    print(f"char accuracy  : {summary['overall_character_accuracy'] * 100:.2f}%")
    print(f"perfect cards  : {summary['perfect_cards'] * 100:.2f}%")
    print(f"mean latency   : {summary['mean_latency_ms']:.0f} ms")
    for key, value in summary["field_exact_match"].items():
        print(f"  {key:15} {value * 100:5.1f}%  ({summary['field_character_accuracy'][key] * 100:5.1f}% chars)")

    if args.out:
        report_path = Path(args.out)
        report_path.parent.mkdir(parents=True, exist_ok=True)
        report_path.write_text(
            to_markdown(summary, title=args.title, dataset=str(dataset), settings=settings),
            encoding="utf-8",
        )
        print(f"report → {report_path}")
    if args.json_out:
        Path(args.json_out).write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"metrics → {args.json_out}")
    return 0 if summary["overall_exact_match"] >= 0.95 else 1


if __name__ == "__main__":
    raise SystemExit(main())
