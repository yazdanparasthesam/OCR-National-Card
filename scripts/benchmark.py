"""Accuracy benchmark for the OCR pipeline.

Thin command-line wrapper around :mod:`nidocr.accuracy` — the same measurement the
Streamlit «دقت» tab and ``nidocr bench`` use, so a number printed here and a number
shown in the UI can never disagree.

It reads a folder of card images with ground-truth JSON (generated by
``scripts/generate_synthetic_cards.py`` or annotated by you) and reports, **per
field and overall**, the exact-match rate, the character accuracy, the mean
confidence and the validator pass rate.

Examples::

    python scripts/benchmark.py --generate 30 --difficulty clean
    python scripts/benchmark.py --generate 30 --difficulty photo --out reports/benchmark_photo.md
    python scripts/benchmark.py --dataset data/samples            # your own folder
    python scripts/benchmark.py --dataset /tmp/final_clean --json-out /tmp/clean.json
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from nidocr.accuracy import AccuracyReport, evaluate, load_dataset  # noqa: E402,F401
from nidocr.config import PROJECT_ROOT, Settings  # noqa: E402
from nidocr.pipeline import NationalCardOCR  # noqa: E402


def run(
    records: list[tuple[Path, dict]],
    *,
    ocr: NationalCardOCR,
    difficulties: list[str] | None = None,
    difficulty: str | None = None,
    verbose: bool = True,
) -> AccuracyReport:
    """Measure ``records`` and print a progress line per card when ``verbose``.

    ``difficulties`` keeps only the records whose ground truth carries one of the
    given ``difficulty`` values (useful for mixed datasets); ``difficulty`` is the
    label written in the report header.
    """
    selected = [
        (image, payload)
        for image, payload in records
        if not difficulties or payload.get("difficulty", "custom") in difficulties
    ]
    total = len(selected)

    def progress(done: int, _total: int, label: str) -> None:
        """Print one progress line per card (only when ``verbose``)."""
        if verbose:
            print(f"  [{done:3}/{total}] {label}")

    report = evaluate(
        selected,
        ocr=ocr,
        difficulty=difficulty or "custom",
        progress=progress if verbose else None,
    )
    if verbose and report.failures:
        print(f"\n  {len(report.failures)} misread field(s) recorded")
    return report


def to_markdown(report: AccuracyReport, *, title: str, dataset: str, settings: Settings) -> str:
    """Format a report as the markdown file committed under ``reports/``."""
    header = [
        f"- dataset: `{dataset}`",
        f"- engine: tesseract (`{settings.languages}`) + glyph digit classifier",
    ]
    body = report.to_markdown(title=title).splitlines()
    # ``report.to_markdown`` starts with the title and the raw counters; splice the
    # dataset/engine lines right after the counters so the file keeps its old shape.
    rest = body[1:]
    while rest and not rest[0].strip():
        rest = rest[1:]
    out = body[:1] + [""] + header + [""] + rest
    return "\n".join(out) + ("\n" if not out[-1].endswith("\n") else "")


def _dataset_label(dataset: Path) -> str:
    """Short, portable name for the report header (repo-relative when possible)."""
    try:
        return str(dataset.resolve().relative_to(PROJECT_ROOT))
    except ValueError:
        return dataset.name


def main() -> int:
    """CLI of the benchmark: optional dataset generation, run, report, optional JSON."""
    parser = argparse.ArgumentParser(description="Benchmark the national-card OCR pipeline")
    parser.add_argument("--dataset", default=None, help="folder with images + ground-truth JSON")
    parser.add_argument("--generate", type=int, default=0, help="generate N synthetic cards first")
    parser.add_argument("--difficulty", default="photo", choices=["clean", "photo", "hard"])
    parser.add_argument("--out", default=None, help="write a markdown report here")
    parser.add_argument("--json-out", default=None, help="write raw metrics as JSON")
    parser.add_argument("--title", default="National card OCR benchmark")
    parser.add_argument("--no-cache", action="store_true", help="disable the OCR result cache")
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args()

    settings = Settings()
    if args.no_cache:
        settings = settings.model_copy(update={"cache_ocr": False})

    dataset = Path(args.dataset) if args.dataset else PROJECT_ROOT / "data" / "bench" / args.difficulty
    if args.generate:
        from nidocr.synthetic.renderer import save_dataset

        save_dataset(dataset, count=args.generate, difficulty=args.difficulty, seed=42)
        print(f"generated {args.generate} cards in {dataset}")

    records = load_dataset(dataset)
    if not records:
        print(f"no annotated cards found in {dataset}")
        return 2
    print(f"benchmarking {len(records)} cards from {dataset}")

    ocr = NationalCardOCR(settings)
    report = run(records, ocr=ocr, difficulty=args.difficulty, verbose=not args.quiet)

    print(f"\nexact match    : {report.exact * 100:.2f}%")
    print(f"char accuracy  : {report.characters * 100:.2f}%")
    print(f"perfect cards  : {report.perfect_cards * 100:.2f}%")
    print(f"mean latency   : {report.mean_latency_ms:.0f} ms")
    for row in report.fields:
        print(f"  {row.key:15} {row.exact * 100:5.1f}%  ({row.characters * 100:5.1f}% chars)")

    if args.out:
        report_path = Path(args.out)
        report_path.parent.mkdir(parents=True, exist_ok=True)
        report_path.write_text(
            to_markdown(report, title=args.title, dataset=_dataset_label(dataset), settings=settings),
            encoding="utf-8",
        )
        print(f"report → {report_path}")
    if args.json_out:
        Path(args.json_out).write_text(
            json.dumps(report.as_dict(), ensure_ascii=False, indent=2), encoding="utf-8"
        )
        print(f"metrics → {args.json_out}")
    return 0 if report.exact >= 0.95 else 1


if __name__ == "__main__":
    raise SystemExit(main())
